function getInitialLanguage() {

  // 1. user previously selected language
  sessionStorage.getItem("lang")
  if (saved) return saved;

  // 2. detect browser language
  const browserLang = navigator.language.toLowerCase();

  if (browserLang.startsWith("de")) return "de";

  // 3. fallback (business default)
  return "de";
}

function setLanguage(lang) {
  // Update text content
  const elements = document.querySelectorAll("[data-i18n]");

  elements.forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.innerHTML = translations[lang][key];
  });

  // Update current language button
  const currentLangBtn = document.getElementById("current-language");
  currentLangBtn.textContent = languageLabels[lang];

  // Rebuild dropdown menu (exclude current language)
  const menu = document.getElementById("language-menu");
  menu.innerHTML = "";

  Object.keys(languageLabels).forEach(code => {
    if (code !== lang) {
      const link = document.createElement("a");
      link.href = "#";
      link.textContent = languageLabels[code];
      link.onclick = function(e) {
        e.preventDefault();
        setLanguage(code);
      };
      menu.appendChild(link);
    }
  });

  // Save selection
  sessionStorage.setItem("lang", lang);
}

